    const f = floatRef.current;
    if (f) {
      const k = 1 - easeInOutCubic(getCubeProgress());
      const t = floatOffset.current + state.clock.getElapsedTime();
      f.rotation.x = (Math.cos((t / 4) * FLOAT_SPEED) / 8) * FLOAT_ROTATION * k;
      f.rotation.y = (Math.sin((t / 4) * FLOAT_SPEED) / 8) * FLOAT_ROTATION * k;
      f.rotation.z = (Math.sin((t / 4) * FLOAT_SPEED) / 20) * FLOAT_ROTATION * k;
      const y = THREE.MathUtils.mapLinear(Math.sin((t / 4) * FLOAT_SPEED) / 10, -0.1, 0.1, 0, 1);
      f.position.y = y * FLOAT_INTENSITY * k;
      f.updateMatrix();
    }
    // El cubo sube al entrar en el modo y baja al salir, al ritmo del vuelo de cámara
